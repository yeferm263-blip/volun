// Helper to calculate which badges are unlocked for a volunteer
export function checkBadgeUnlocked(
  badge: AchievementBadge,
  stats: {
    approvedHours: number;
    approvedMinutes: number;
    totalSubmissions: number;
    reviewsCount?: number;
    ratingAvg?: number;
  }
): boolean {
  const { approvedHours, totalSubmissions, reviewsCount = 0, ratingAvg = 5.0 } = stats;

  if (badge.unlockedAt.hours && approvedHours < badge.unlockedAt.hours) {
    return false;
  }

  if (badge.unlockedAt.submissionsCount && totalSubmissions < badge.unlockedAt.submissionsCount) {
    return false;
  }

  if (badge.unlockedAt.reviewsCount && reviewsCount < badge.unlockedAt.reviewsCount) {
    return false;
  }

  if (badge.unlockedAt.ratingMin && (ratingAvg < badge.unlockedAt.ratingMin || reviewsCount === 0)) {
    return false;
  }

  return true;
}
